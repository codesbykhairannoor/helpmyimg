// Flatten to reverse lookup (slug -> {lang, tool})
const REVERSE_LOOKUP: Record<string, { lang: string; tool: InternalTool }> = {};

Object.entries(SLUG_MAP).forEach(([lang, tools]) => {
  Object.entries(tools).forEach(([tool, slug]) => {
    REVERSE_LOOKUP[slug] = { lang, tool: tool as InternalTool };
  });
});

/**
 * Get internal tool name from a localized slug.
 */
export function getToolFromSlug(slug: string, _oldLang?: string): InternalTool {
  if (REVERSE_LOOKUP[slug]) {
    return REVERSE_LOOKUP[slug].tool;
  }
  if (LEGACY_VARIANT_ALIASES[slug]) {
    return LEGACY_VARIANT_ALIASES[slug];
  }

  // Fallback & legacy alias resolution
  if (slug === 'magic-brush' || slug === 'manual-brush' || slug === 'kuas-ajaib' || slug === 'brush') return 'brush';
  if (slug === 'remove-background' || slug === 'remove-logo' || slug === 'removelogo' || slug === 'remove-person-from-photo' || slug === 'remove-person' || slug === 'removeperson') return 'remove';
  if (slug === 'change-background' || slug === 'change-background-white' || slug === 'change-background-to-white' || slug === 'colorwhite') return 'color';
  if (slug === 'watermark-image' || slug === 'batch-watermark-photos' || slug === 'bulk-watermark' || slug === 'watermarkbulk') return 'watermark';
  if (slug === 'compress-image' || slug === 'compress-image-to-100kb' || slug === 'compress100kb' || slug === 'compress-image-to-50kb' || slug === 'compress50kb' || slug === 'compress-image-to-200kb' || slug === 'compress-200kb' || slug === 'compress200kb') return 'compress';
  if (slug === 'convert-image' || slug === 'convert-webp-to-jpg' || slug === 'convert-to-webp' || slug === 'convertwebp') return 'convert';
  if (slug === 'resize-image' || slug === 'resize-image-for-instagram' || slug === 'resizeig' || slug === 'resize-passport' || slug === 'resizepassport' || slug === 'passport-photo') return 'resize';
  if (slug === 'crop-image') return 'crop';
  if (slug === 'rotate-image') return 'rotate';
  if (slug === 'image-color-picker') return 'picker';
  if (slug === 'blur-face' || slug === 'blur-license-plate' || slug === 'blurplate') return 'blurface';
  if (slug === 'advanced-editor') return 'design';
  if (slug === 'ai-metadata-cleaner' || slug === 'c2pa-remover' || slug === 'metadata-cleaner') return 'metadata';
  if (slug === 'edit-exif' || slug === 'edit-exif-foto' || slug === 'camera-metadata') return 'editexif';

  return 'remove';
}

/**
 * Get localized slug for a given tool and language.
 */
export function getLocalizedSlug(tool: InternalTool, lang: string): string {
  if (SLUG_MAP[lang] && SLUG_MAP[lang][tool]) {
    return SLUG_MAP[lang][tool];
  }

  return FALLBACK_SLUGS[tool] || FALLBACK_SLUGS['remove'];
}
